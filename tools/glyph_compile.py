#!/usr/bin/env python3
"""Compile font/glyphs.txt (hand-drawn pixel art) into src/c/glyphs.h. If the settings
page source is present (it isn't in the public repository), also embed the same art
into it (config/page.html -> config/index.html).

Pixel art legend:  '#' = full ink   '+' = anti-alias (half ink)   '.' = empty
Every glyph is GLYPH_ROWS tall. Rows 0..16 are the cap height, rows 17..18 hold
descenders. Glyph row 8 lands on the flap split line and is never visible.

Usage:
  glyph_compile.py                  write src/c/glyphs.h (and config/index.html, if present)
  glyph_compile.py --preview OUT    also render an enlarged preview sheet (needs Pillow)
  glyph_compile.py --logo OUT       also render the VESTA logo image (needs Pillow)
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'font', 'glyphs.txt')
OUT = os.path.join(ROOT, 'src', 'c', 'glyphs.h')
PAGE_SRC = os.path.join(ROOT, 'config', 'page.html')
PAGE_OUT = os.path.join(ROOT, 'config', 'index.html')
GLYPH_ROWS = 19
MAX_W = 11

# Flap order on the drum, following Vestaboard character codes (black board).
# Each flap has a one-byte ASCII key used by the C code to spell board text:
#   '*' = heart (red)   '^' = degree sign
#   lowercase r o y g b v = red/orange/yellow/green/blue/violet color chips
#   'w' = the filled panel, the opposite of blank (white on dark, black on light)
FLAPS = (
    [' '] + list('ABCDEFGHIJKLMNOPQRSTUVWXYZ') + list('1234567890') +
    list('!@#$()-+&=;:\'"%,./?') + ['^', '*'] + list('roygbvw')
)
ART_NAME = {'^': '°'}  # name used in glyphs.txt when it differs from the key


def load():
    glyphs, cur = {}, None
    with open(SRC, encoding='utf-8') as f:
        for line in f:
            line = line.rstrip('\n')
            if line.startswith('== '):
                cur = line[3:]
                glyphs[cur] = []
            elif line.strip() and cur is not None:
                glyphs[cur].append(line.strip())
    for name, rows in glyphs.items():
        if len(rows) != GLYPH_ROWS:
            sys.exit('glyph %r: %d rows, expected %d' % (name, len(rows), GLYPH_ROWS))
        widths = {len(r) for r in rows}
        if len(widths) != 1 or widths.pop() > MAX_W:
            sys.exit('glyph %r: ragged or too wide' % name)
    return glyphs


def pack(rows):
    out = []
    for r in rows:
        v = 0
        for x, c in enumerate(r):
            v |= {'.': 0, '+': 1, '#': 2}[c] << (2 * x)
        out.append(v)
    return out


def write_header(glyphs):
    lines = [
        '// Generated by tools/glyph_compile.py from font/glyphs.txt -- do not edit.',
        '#pragma once',
        '#include <pebble.h>',
        '',
        '#define FLAP_COUNT %d' % len(FLAPS),
        '#define GLYPH_ROWS %d' % GLYPH_ROWS,
        '',
        'typedef struct {',
        '  uint8_t width;                // 0 = no ink (blank or color chip)',
        '  uint32_t rows[GLYPH_ROWS];    // 2 bits per pixel: 0 empty, 1 anti-alias, 2 ink',
        '} Glyph;',
        '',
        '// ASCII key for each flap, in drum order.',
        'static const char FLAP_KEYS[FLAP_COUNT + 1] = "%s";' %
        ''.join(k.replace('\\', '\\\\').replace('"', '\\"') for k in FLAPS),
        '',
        'static const Glyph GLYPHS[FLAP_COUNT] = {',
    ]
    for key in FLAPS:
        art = glyphs.get(ART_NAME.get(key, key))
        label = ART_NAME.get(key, key)
        if art is None:
            lines.append('  { 0, { 0 } },  // %r' % label)
            continue
        vals = ', '.join('0x%06x' % v for v in pack(art))
        lines.append('  { %d, { %s } },  // %s' % (len(art[0]), vals, label))
    lines.append('};')
    with open(OUT, 'w') as f:
        f.write('\n'.join(lines) + '\n')


def write_page(glyphs):
    art = {k: glyphs[ART_NAME.get(k, k)] for k in FLAPS if ART_NAME.get(k, k) in glyphs}
    data = 'const FLAP_KEYS = %s;\nconst GLYPH_ART = %s;' % (
        json.dumps(FLAPS, ensure_ascii=False), json.dumps(art, ensure_ascii=False, separators=(',', ':')))
    with open(PAGE_SRC, encoding='utf-8') as f:
        page = f.read()
    if page.count('/*__GLYPH_DATA__*/') != 1:
        sys.exit('config/page.html: missing glyph data marker')
    with open(PAGE_OUT, 'w', encoding='utf-8') as f:
        f.write(page.replace('/*__GLYPH_DATA__*/', data))


