# Preview: mirrors the tile renderer in src/c/main.c so designs can be judged
# without the emulator.

BLACK, DGRAY, LGRAY, WHITE = (0, 0, 0), (85, 85, 85), (170, 170, 170), (255, 255, 255)
CHIP = {'r': (255, 0, 0), 'o': (255, 85, 0), 'y': (255, 255, 0), 'g': (85, 170, 85),
        'b': (0, 85, 170), 'v': (85, 0, 170), 'w': (255, 255, 255)}
TILE_W, TILE_H = BASALT.tile_w, BASALT.tile_h
IN_W, IN_H = BASALT.in_w, BASALT.in_h
SPLIT = BASALT.split
GLYPH_TOP = BASALT.glyph_top
FLAP_EDGE = BASALT.flap_edge
FLAP_EDGE_LOW = BASALT.flap_edge_low
FLIP_NONE, FLIP_TOP, FLIP_BOTTOM = 0, 1, 2
FACE, BEZEL, SPLIT_C, EDGE_C = BLACK, DGRAY, BLACK, DGRAY


def ink(key, glyphs, gx, gy, geo=BASALT):
    """Color of a glyph pixel at interior coords, or None for background."""
    if key in CHIP:
        return CHIP[key]
    art = glyphs.get(ART_NAME.get(key, key))
    if not art:
        return None
    w = len(art[0])
    x, y = gx - (geo.in_w - w) // 2, gy - geo.glyph_top
    if not (0 <= x < w and 0 <= y < geo.glyph_rows):
        return None
    c = art[y][x]
    if key == '*':
        return {'#': (255, 0, 0), '+': (170, 0, 0)}.get(c)
    return {'#': WHITE, '+': LGRAY}.get(c)


def dim(c):
    return None if c is None else tuple(max(v - 85, 0) for v in c)


def face(key, glyphs, row, geo, dimmed=False):
    """One interior row of a flap's artwork."""
    out = []
    for x in range(geo.in_w):
        c = ink(key, glyphs, x, row, geo)
        out.append((dim(c) if dimmed else c) or FACE)
    return out


def spread(dist, span, geo):
    """Extra pixels on each side of the falling flap, dist rows from its hinge."""
    return (2 * geo.flap_over * dist + span) // (2 * span)


def interior_row(cur, nxt, glyphs, y, flip, geo=BASALT):
    """{interior x: color} for interior row y, bezel columns included. While a flap
    falls toward the viewer its free edge widens, so x can reach past the tile."""
    row = {-1: BEZEL, geo.in_w: BEZEL}

    def plain(key, r, dimmed=False):
        row.update(enumerate(face(key, glyphs, r, geo, dimmed)))

    def flap(key, src, e):
        # Falling flap: artwork stretched across its widened width, outlined in bezel.
        art, w = face(key, glyphs, src, geo), geo.in_w + 2 * e
        row[-1 - e] = row[geo.in_w + e] = EDGE_C
        for x in range(w):
            row[x - e] = art[x * geo.in_w // w]

    def edge(e):
        for x in range(-1 - e, geo.in_w + e + 1):
            row[x] = EDGE_C

    s, top, low = geo.split, geo.flap_edge, geo.flap_edge_low
    if y == s:
        row.update((x, SPLIT_C) for x in range(geo.in_w))
    elif flip == FLIP_TOP and y < s:
        if y < top:                     # next flap revealed, in the falling flap's shadow
            plain(nxt, y, True)
        elif y == top:                  # leading edge of the falling flap
            edge(spread(s - y, s - top, geo))
        else:                           # falling flap: current top half, foreshortened
            flap(cur, (y - top - 1) * s // (s - top - 1), spread(s - y, s - top, geo))
    elif flip == FLIP_BOTTOM:
        if y < s:
            plain(nxt, y)
        elif y > low:                   # current bottom half, in the falling flap's shadow
            plain(cur, y, True)
        elif y == low:
            edge(spread(y - s, low - s, geo))
        else:                           # falling flap: next bottom half, foreshortened
            flap(nxt, s + 1 + (y - s - 1) * (geo.in_h - s - 1) // (low - s - 1), spread(y - s, low - s, geo))
    else:
        plain(cur, y)
    return row


def draw_tile(px, ox, oy, cur, nxt, glyphs, flip=FLIP_NONE, geo=BASALT):
    for y in range(geo.tile_h):
        if y in (0, geo.tile_h - 1):
            for x in range(geo.tile_w):
                px[ox + x, oy + y] = BEZEL
            continue
        for x, c in interior_row(cur, nxt, glyphs, y - 1, flip, geo).items():
            px[ox + 1 + x, oy + y] = c


def preview(glyphs, path, geo=BASALT, flips=(FLIP_TOP,)):
    """Each flap at rest, then each flip frame to the next flap below it."""
    from PIL import Image
    keys = [k for k in FLAPS]
    cols = 13
    rows = (len(keys) + cols - 1) // cols
    frames = 1 + len(flips)
    margin = 3 + geo.flap_over
    pitch_x, pitch_y = geo.tile_w + 3 + 2 * geo.flap_over, geo.tile_h + 10
    w, h = cols * pitch_x + margin, (rows * frames) * pitch_y + 10
    im = Image.new('RGB', (w, h), BLACK)
    px = im.load()
    for i, k in enumerate(keys):
        cx, cy = margin + (i % cols) * pitch_x, 5 + (i // cols) * frames * pitch_y
        draw_tile(px, cx, cy, k, k, glyphs, geo=geo)
        nxt = keys[(i + 1) % len(keys)]
        for f, flip in enumerate(flips, 1):
            draw_tile(px, cx, cy + f * pitch_y, k, nxt, glyphs, flip=flip, geo=geo)
    im.resize((w * 5, h * 5), Image.NEAREST).save(path)


def logo(glyphs, path):
    from PIL import Image
    text, margin, gap, scale = 'VESTA', 6, 3, 8
    w = len(text) * TILE_W + (len(text) - 1) * gap + 2 * margin
    h = TILE_H + 2 * margin
    im = Image.new('RGB', (w, h), BLACK)
    px = im.load()
    for i, ch in enumerate(text):
        draw_tile(px, margin + i * (TILE_W + gap), margin, ch, ch, glyphs)
    im.resize((w * scale, h * scale), Image.NEAREST).save(path)


def main():
    glyphs, glyphs_hd = load(BASALT), load(HD)
    for geo, g in ((BASALT, glyphs), (HD, glyphs_hd)):
        missing = [k for k in FLAPS if k != ' ' and k not in CHIP and ART_NAME.get(k, k) not in g]
        if missing:
            sys.exit('%s: missing glyphs: %s' % (geo.src, missing))
    write_header(glyphs, glyphs_hd)
    print('wrote', OUT)
    if os.path.exists(PAGE_SRC):
        write_page(glyphs, glyphs_hd)
        print('wrote', PAGE_OUT)
    if '--preview' in sys.argv:
        out = sys.argv[sys.argv.index('--preview') + 1]
        preview(glyphs, out)
        print('wrote', out)
    if '--preview-hd' in sys.argv:
        out = sys.argv[sys.argv.index('--preview-hd') + 1]
        preview(glyphs_hd, out, HD, (FLIP_TOP, FLIP_BOTTOM))
        print('wrote', out)
    if '--logo' in sys.argv:
        out = sys.argv[sys.argv.index('--logo') + 1]
        logo(glyphs, out)
        print('wrote', out)


if __name__ == '__main__':
    main()
