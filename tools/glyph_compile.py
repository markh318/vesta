#!/usr/bin/env python3
"""Compile the hand-drawn pixel art in font/ into src/c/glyphs.h. If the settings
page source is present (it isn't in the public repository), also embed the same art
into it (config/page.html -> config/index.html).

There are two glyph sets:
  font/glyphs.txt      Pebble Time (144x168). 19 rows: cap height 0..16, descenders
                       17..18, and row 8 lands on the flap split line.
  font/glyphs_hd.txt   Pebble Time 2 and Round 2. 28 rows: cap height 0..24,
                       descenders 25..27, and row 12 lands on the split line.
The row on the split line is never visible.

Pixel art legend:  '#' = full ink   '+' = anti-alias (half ink)   '.' = empty

Usage:
  glyph_compile.py                     write src/c/glyphs.h (and config/index.html, if present)
  glyph_compile.py --preview OUT       also render an enlarged preview sheet (needs Pillow)
  glyph_compile.py --preview-hd OUT    the same for the high-resolution set
  glyph_compile.py --logo OUT          also render the VESTA logo image (needs Pillow)
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'font', 'glyphs.txt')
SRC_HD = os.path.join(ROOT, 'font', 'glyphs_hd.txt')
OUT = os.path.join(ROOT, 'src', 'c', 'glyphs.h')
PAGE_SRC = os.path.join(ROOT, 'config', 'page.html')
PAGE_OUT = os.path.join(ROOT, 'config', 'index.html')
GLYPH_ROWS = 19
MAX_W = 11

# Flap order on the drum, following Vestaboard character codes (black board).
# Each flap has a one-byte ASCII key used by the C code to spell board text:
#   '*' = heart (red)   '^' = degree sign
#   lowercase r o y g b v = red/orange/yellow/green/blue/violet color chips
#   'w' = the filled panel, the opposite of blank (white on dark, black on light)
FLAPS = (
    [' '] + list('ABCDEFGHIJKLMNOPQRSTUVWXYZ') + list('1234567890') +
    list('!@#$()-+&=;:\'"%,./?') + ['^', '*'] + list('roygbvw')
)
ART_NAME = {'^': '°'}  # name used in glyphs.txt when it differs from the key


class Geometry:
    """Tile and glyph measurements for one display class; must match src/c/main.c."""

    def __init__(self, src, glyph_rows, split_row, max_w, tile_w, tile_h, flap_edge, flap_over):
        self.src, self.glyph_rows, self.max_w = src, glyph_rows, max_w
        self.tile_w, self.tile_h = tile_w, tile_h
        self.in_w, self.in_h = tile_w - 2, tile_h - 2
        self.split = self.in_h // 2                      # interior row of the split line
        self.glyph_top = self.split - split_row          # glyph row split_row sits on the split
        self.flap_edge = flap_edge                       # interior row of the falling flap's edge
        self.flap_edge_low = 2 * self.split - flap_edge  # the same edge, past horizontal
        self.flap_over = flap_over                       # px the flap's edge reaches past the tile


BASALT = Geometry(SRC, GLYPH_ROWS, 8, MAX_W, 15, 31, 9, 0)
HD = Geometry(SRC_HD, 28, 12, 16, 21, 43, 13, 1)


def load(geo=BASALT):
    glyphs, cur = {}, None
    with open(geo.src, encoding='utf-8') as f:
        for line in f:
            line = line.rstrip('\n')
            if line.startswith('== '):
                cur = line[3:]
                glyphs[cur] = []
            elif line.strip() and cur is not None:
                glyphs[cur].append(line.strip())
    for name, rows in glyphs.items():
        if len(rows) != geo.glyph_rows:
            sys.exit('%s: glyph %r: %d rows, expected %d' % (geo.src, name, len(rows), geo.glyph_rows))
        widths = {len(r) for r in rows}
        if len(widths) != 1 or widths.pop() > geo.max_w:
            sys.exit('%s: glyph %r: ragged or too wide' % (geo.src, name))
    return glyphs


def pack(rows):
    out = []
    for r in rows:
        v = 0
        for x, c in enumerate(r):
            v |= {'.': 0, '+': 1, '#': 2}[c] << (2 * x)
        out.append(v)
    return out


def glyph_table(glyphs, digits):
    lines = ['static const Glyph GLYPHS[FLAP_COUNT] = {']
    for key in FLAPS:
        art = glyphs.get(ART_NAME.get(key, key))
        label = ART_NAME.get(key, key)
        if art is None:
            lines.append('  { 0, { 0 } },  // %r' % label)
            continue
        vals = ', '.join('0x%0*x' % (digits, v) for v in pack(art))
        lines.append('  { %d, { %s } },  // %s' % (len(art[0]), vals, label))
    lines.append('};')
    return lines


def write_header(glyphs, glyphs_hd):
    lines = [
        '// Generated by tools/glyph_compile.py from font/glyphs.txt and font/glyphs_hd.txt',
        '// -- do not edit.',
        '#pragma once',
        '#include <pebble.h>',
        '',
        '#define FLAP_COUNT %d' % len(FLAPS),
        '',
        '// ASCII key for each flap, in drum order.',
        'static const char FLAP_KEYS[FLAP_COUNT + 1] = "%s";' %
        ''.join(k.replace('\\', '\\\\').replace('"', '\\"') for k in FLAPS),
        '',
        '// The Pebble Time 2 and Round 2 use the high-resolution set.',
        '#if PBL_DISPLAY_WIDTH >= 200',
        '#define GLYPH_ROWS %d' % HD.glyph_rows,
        '#define GLYPH_SPLIT_ROW %d    // glyph row on the split line' % (HD.split - HD.glyph_top),
        '#else',
        '#define GLYPH_ROWS %d' % BASALT.glyph_rows,
        '#define GLYPH_SPLIT_ROW %d     // glyph row on the split line' % (BASALT.split - BASALT.glyph_top),
        '#endif',
        '',
        'typedef struct {',
        '  uint8_t width;                // 0 = no ink (blank or color chip)',
        '  uint32_t rows[GLYPH_ROWS];    // 2 bits per pixel: 0 empty, 1 anti-alias, 2 ink',
        '} Glyph;',
        '',
        '#if PBL_DISPLAY_WIDTH >= 200',
    ] + glyph_table(glyphs_hd, 8) + ['#else'] + glyph_table(glyphs, 6) + ['#endif']
    with open(OUT, 'w') as f:
        f.write('\n'.join(lines) + '\n')


def write_page(glyphs, glyphs_hd):
    def art(g):
        return json.dumps({k: g[ART_NAME.get(k, k)] for k in FLAPS if ART_NAME.get(k, k) in g},
                          ensure_ascii=False, separators=(',', ':'))
    data = 'const FLAP_KEYS = %s;\nconst GLYPH_ART = %s;\nconst GLYPH_ART_HD = %s;' % (
        json.dumps(FLAPS, ensure_ascii=False), art(glyphs), art(glyphs_hd))
    with open(PAGE_SRC, encoding='utf-8') as f:
        page = f.read()
    if page.count('/*__GLYPH_DATA__*/') != 1:
        sys.exit('config/page.html: missing glyph data marker')
    with open(PAGE_OUT, 'w', encoding='utf-8') as f:
        f.write(page.replace('/*__GLYPH_DATA__*/', data))


