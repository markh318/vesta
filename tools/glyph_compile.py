# Preview: mirrors the tile renderer in src/c/main.c so designs can be judged
# without the emulator.

BLACK, DGRAY, LGRAY, WHITE = (0, 0, 0), (85, 85, 85), (170, 170, 170), (255, 255, 255)
CHIP = {'r': (255, 0, 0), 'o': (255, 85, 0), 'y': (255, 255, 0), 'g': (85, 170, 85),
        'b': (0, 85, 170), 'v': (85, 0, 170), 'w': (255, 255, 255)}
TILE_W, TILE_H = 15, 31
IN_W, IN_H = TILE_W - 2, TILE_H - 2
SPLIT = IN_H // 2            # interior row of the split line
GLYPH_TOP = SPLIT - 8        # glyph row 8 sits on the split
FLAP_EDGE = 9                # interior row of the falling flap's leading edge


def ink(key, glyphs, gx, gy):
    """Color of a glyph pixel at interior coords, or None for background."""
    if key in CHIP:
        return CHIP[key]
    art = glyphs.get(ART_NAME.get(key, key))
    if not art:
        return None
    w = len(art[0])
    x, y = gx - (IN_W - w) // 2, gy - GLYPH_TOP
    if not (0 <= x < w and 0 <= y < GLYPH_ROWS):
        return None
    c = art[y][x]
    if key == '*':
        return {'#': (255, 0, 0), '+': (170, 0, 0)}.get(c)
    return {'#': WHITE, '+': LGRAY}.get(c)


def dim(c):
    return None if c is None else tuple(max(v - 85, 0) for v in c)


FACE, BEZEL, SPLIT_C, EDGE_C = BLACK, DGRAY, BLACK, DGRAY


def interior(cur, nxt, glyphs, x, y, flipping):
    if not flipping or y >= SPLIT:
        return ink(cur, glyphs, x, y)
    if y < FLAP_EDGE:                   # next flap revealed, in the falling flap's shadow
        return dim(ink(nxt, glyphs, x, y))
    if y == FLAP_EDGE:                  # leading edge of the falling flap
        return EDGE_C
    # falling flap: current top half, foreshortened toward the hinge
    span = SPLIT - FLAP_EDGE - 1
    src = (y - FLAP_EDGE - 1) * SPLIT // span
    return ink(cur, glyphs, x, src)


def draw_tile(px, ox, oy, cur, nxt, glyphs, flipping=False):
    for y in range(TILE_H):
        for x in range(TILE_W):
            edge = x in (0, TILE_W - 1) or y in (0, TILE_H - 1)
            if edge:
                c = BEZEL
            elif y - 1 == SPLIT:
                c = SPLIT_C
            else:
                c = interior(cur, nxt, glyphs, x - 1, y - 1, flipping) or FACE
            px[ox + x, oy + y] = c


def preview(glyphs, path):
    from PIL import Image
    keys = [k for k in FLAPS]
    cols = 13
    rows = (len(keys) + cols - 1) // cols
    pitch_x, pitch_y = TILE_W + 3, TILE_H + 10
    w, h = cols * pitch_x + 3, (rows * 2) * pitch_y + 10
    im = Image.new('RGB', (w, h), BLACK)
    px = im.load()
    for i, k in enumerate(keys):
        cx, cy = 3 + (i % cols) * pitch_x, 5 + (i // cols) * 2 * pitch_y
        draw_tile(px, cx, cy, k, k, glyphs)
        nxt = keys[(i + 1) % len(keys)]
        draw_tile(px, cx, cy + pitch_y, k, nxt, glyphs, flipping=True)
    im.resize((w * 5, h * 5), Image.NEAREST).save(path)


def logo(glyphs, path):
    from PIL import Image
    text, margin, gap, scale = 'VESTA', 6, 3, 8
    w = len(text) * TILE_W + (len(text) - 1) * gap + 2 * margin
    h = TILE_H + 2 * margin
    im = Image.new('RGB', (w, h), BLACK)
    px = im.load()
    for i, ch in enumerate(text):
        draw_tile(px, margin + i * (TILE_W + gap), margin, ch, ch, glyphs)
    im.resize((w * scale, h * scale), Image.NEAREST).save(path)


def main():
    glyphs = load()
    missing = [k for k in FLAPS if k != ' ' and k not in CHIP and ART_NAME.get(k, k) not in glyphs]
    if missing:
        sys.exit('missing glyphs: %s' % missing)
    write_header(glyphs)
    print('wrote', OUT)
    if os.path.exists(PAGE_SRC):
        write_page(glyphs)
        print('wrote', PAGE_OUT)
    if '--preview' in sys.argv:
        out = sys.argv[sys.argv.index('--preview') + 1]
        preview(glyphs, out)
        print('wrote', out)
    if '--logo' in sys.argv:
        out = sys.argv[sys.argv.index('--logo') + 1]
        logo(glyphs, out)
        print('wrote', out)


if __name__ == '__main__':
    main()
